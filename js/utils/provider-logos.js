/**
 * Returns the provider logo SVG string for a given model or provider key
 */
export function getProviderLogoSvg(providerKey, size = 32, cls = "") {
  const norm = (providerKey || "").toLowerCase();
  if (norm.includes("anthropic") || norm.includes("claude")) {
    return providerLogos.anthropic(size, cls);
  }
  if (norm.includes("openai") || norm.includes("gpt") || norm.includes("o3")) {
    return providerLogos.openai(size, cls);
  }
  if (norm.includes("google") || norm.includes("gemini")) {
    return providerLogos.google(size, cls);
  }
  if (norm.includes("deepseek")) {
    return providerLogos.deepseek(size, cls);
  }
  if (norm.includes("groq") || norm.includes("meta") || norm.includes("llama")) {
    return providerLogos.groq(size, cls);
  }
  return providerLogos.openai(size, cls);
}

